from pydantic import BaseModel, Field


class ProteinSearchResult(BaseModel):
    """Ranked protein match from biological repository search."""

    accession: str = Field(description="Primary UniProt accession, e.g. P68871")
    entry_name: str | None = Field(default=None, description="UniProt entry identifier, e.g. HBB_HUMAN")
    protein_name: str = Field(description="Recommended or approved protein name")
    gene_name: str | None = Field(default=None, description="Primary associated gene symbol")
    organism: str = Field(description="Scientific or common organism name")
    taxid: int | None = Field(default=None, description="NCBI Taxonomy identifier")
    length: int = Field(description="Amino acid sequence length")
    reviewed: bool = Field(default=True, description="True for Swiss-Prot reviewed, False for TrEMBL unreviewed")
    score: float | None = Field(default=None, description="Search relevance score")


class ProteinSearchResponse(BaseModel):
    """Payload returned by protein search across UniProtKB."""

    query: str = Field(description="Search input query")
    species: str = Field(description="Organism filter applied")
    total: int = Field(description="Total count of biological matches in UniProtKB")
    results: list[ProteinSearchResult] = Field(description="Ranked list of matching proteins")
    source: str = Field(default="UniProtKB (Swiss-Prot / TrEMBL)", description="Data provider")


class DatabaseReference(BaseModel):
    """Validated external reference link to authoritative biological repository."""

    database: str = Field(description="Database name, e.g. UniProt, RCSB PDB, AlphaFold DB, Ensembl, RefSeq")
    identifier: str = Field(description="Accession number or identifier in target database")
    url: str = Field(description="Direct web link to the record")
    description: str | None = Field(default=None, description="Contextual description")


class PdbStructure(BaseModel):
    """Experimentally determined three-dimensional macromolecular structure from RCSB PDB."""

    pdb_id: str = Field(description="4-character PDB accession identifier, e.g. 4HHB")
    title: str | None = Field(default=None, description="Structure title / deposition description")
    method: str = Field(description="Experimental determination method, e.g. X-ray diffraction, Cryo-EM, Solution NMR")
    resolution_angstrom: float | None = Field(default=None, description="Experimental resolution in Angstroms (if applicable)")
    chains: str | None = Field(default=None, description="Polypeptide chain identifiers and sequence spans")
    deposition_date: str | None = Field(default=None, description="Deposition or release date")
    url: str = Field(description="Direct URL to RCSB PDB entry")
    is_experimental: bool = Field(
        default=True,
        description="Explicit flag confirming structure was experimentally determined (never an in silico prediction)",
    )


class AlphaFoldStructure(BaseModel):
    """Computationally predicted 3D protein structure from AlphaFold Protein Structure Database."""

    entry_id: str = Field(description="AlphaFold DB model identifier, e.g. AF-P68871-F1")
    accession: str = Field(description="UniProt accession")
    global_plddt: float | None = Field(default=None, description="Global predicted Local Distance Difference Test (0-100 score)")
    confidence_category: str | None = Field(
        default=None,
        description="Confidence band: Very High (>90), Confident (70-90), Low (50-70), Very Low (<50)",
    )
    pdb_url: str | None = Field(default=None, description="Download URL for predicted PDB coordinate file")
    cif_url: str | None = Field(default=None, description="Download URL for predicted mmCIF coordinate file")
    url: str = Field(description="Direct link to AlphaFold DB model page")
    is_experimental: bool = Field(
        default=False,
        description="Explicit flag confirming this is a machine learning prediction and NOT an experimental structure",
    )
    prediction_note: str = Field(
        default="Computational in silico model generated by AlphaFold. Not an experimentally determined structure.",
        description="Scientific caveat explaining the in silico origin of the prediction",
    )


class ProteinStructuresResponse(BaseModel):
    """Comprehensive 3D structure overview contrasting experimental PDB records and AlphaFold predictions."""

    accession: str = Field(description="UniProt accession")
    protein_name: str = Field(description="Recommended protein name")
    experimental_structures: list[PdbStructure] = Field(
        default_factory=list,
        description="Experimentally determined atomic structures from RCSB Protein Data Bank",
    )
    predicted_structure: AlphaFoldStructure | None = Field(
        default=None,
        description="Computational structural prediction from AlphaFold Protein Structure Database (if available)",
    )
    experimental_count: int = Field(description="Total count of experimental PDB structures")
    predicted_available: bool = Field(description="Whether a valid AlphaFold prediction is available")
    source: str = Field(default="RCSB PDB & AlphaFold DB via UniProtKB", description="Data provenance")


class AminoAcidComposition(BaseModel):
    """Calculated frequencies and counts of amino acid residues in the sequence."""

    counts: dict[str, int] = Field(description="Absolute count per single-letter amino acid code")
    percentages: dict[str, float] = Field(description="Relative percentage (0-100%) per residue")
    non_canonical: dict[str, int] = Field(
        default_factory=dict,
        description="Counts of any non-standard or ambiguous residues (e.g. B, Z, X, U, O)",
    )


class PhysicochemicalProperties(BaseModel):
    """Genuine computational sequence properties calculated via Biopython."""

    theoretical_molecular_weight_da: float | None = Field(
        default=None,
        description="Theoretical average molecular weight in Daltons (estimated from amino acid composition)",
    )
    isoelectric_point: float | None = Field(
        default=None,
        description="Theoretical isoelectric point (pI), the pH at which net charge is zero",
    )
    aromaticity: float | None = Field(
        default=None,
        description="Relative frequency of aromatic amino acids (Phe, Tyr, Trp)",
    )
    instability_index: float | None = Field(
        default=None,
        description="Guruprasad instability index (>40 indicates predicted in vitro instability)",
    )
    is_stable: bool | None = Field(
        default=None,
        description="True if instability index is < 40.0; False otherwise",
    )
    gravy_score: float | None = Field(
        default=None,
        description="Grand Average of Hydropathy (positive values indicate hydrophobic; negative indicate hydrophilic)",
    )
    charge_at_ph7: float | None = Field(
        default=None,
        description="Estimated net electrostatic charge at physiological pH 7.0",
    )
    computational_notes: list[str] = Field(
        default_factory=list,
        description="Scientific notes detailing computational formulas, limitations, and assumptions",
    )


class ProteinSequenceAnalysisResponse(BaseModel):
    """Complete primary sequence and computational physicochemical profile."""

    accession: str = Field(description="UniProt accession")
    protein_name: str = Field(description="Recommended protein name")
    length: int = Field(description="Sequence length in amino acid residues")
    sequence: str = Field(description="Full standard single-letter amino acid sequence")
    fasta: str = Field(description="Standard formatted FASTA representation")
    composition: AminoAcidComposition = Field(description="Calculated amino acid composition breakdown")
    properties: PhysicochemicalProperties = Field(description="Calculated physicochemical and structural estimations")
    is_canonical_only: bool = Field(description="True if sequence contains exclusively the 20 standard canonical amino acids")
    source: str = Field(default="UniProtKB / Biopython Computational Analysis", description="Attribution")


class ProteinDetailResponse(BaseModel):
    """Comprehensive biological record for an inspected protein."""

    accession: str = Field(description="Primary UniProt accession")
    entry_name: str | None = Field(default=None, description="UniProt entry identifier (e.g. HBB_HUMAN)")
    protein_name: str = Field(description="Recommended or approved protein name")
    gene_name: str | None = Field(default=None, description="Primary associated gene symbol")
    organism: str = Field(description="Organism scientific name")
    taxid: int | None = Field(default=None, description="NCBI Taxonomy ID")
    sequence_length: int = Field(description="Amino acid sequence length")
    sequence: str = Field(description="Primary amino acid sequence")
    mass_da: int | None = Field(default=None, description="Reported UniProt sequence mass in Daltons")
    function_summary: str | None = Field(default=None, description="Curated functional biological summary")
    subcellular_location: str | None = Field(default=None, description="Curated cellular localization")
    protein_existence: str | None = Field(default=None, description="UniProt evidence level for protein existence")
    ptms: list[str] = Field(default_factory=list, description="Curated post-translational modifications")
    features_summary: dict[str, int] = Field(
        default_factory=dict,
        description="Counts of curated structural and functional sequence features (chains, domains, active sites)",
    )
    pdb_structures_count: int = Field(default=0, description="Number of associated experimental PDB entries")
    has_alphafold: bool = Field(default=False, description="Whether an AlphaFold predicted 3D structure is available")
    references: list[DatabaseReference] = Field(default_factory=list, description="Direct cross-database links")
    source: str = Field(description="Attribution of external data source")
    retrieved_at: str = Field(description="ISO timestamp of data retrieval")
    cached: bool = Field(description="Whether response was served from PostgreSQL cache")


class ProteinReferencesResponse(BaseModel):
    """Direct cross-database references for a protein entry."""

    accession: str = Field(description="UniProt accession")
    protein_name: str = Field(description="Protein name")
    references: list[DatabaseReference] = Field(description="List of outbound authoritative links")
    source: str = Field(default="UniProtKB / RCSB PDB / AlphaFold DB", description="Source provider")

