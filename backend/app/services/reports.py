import io
import logging
from datetime import UTC, datetime

from docx import Document
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.schemas.reports import GenerateReportRequest

logger = logging.getLogger(__name__)


class ReportService:
    """Generates professional scientific research reports in PDF and DOCX formats."""

    def generate_pdf(self, req: GenerateReportRequest) -> bytes:
        """Render a publication-ready PDF document in-memory using ReportLab Platypus."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40,
        )

        styles = getSampleStyleSheet()
        primary_color = colors.HexColor("#0f172a")  # Deep Navy
        secondary_color = colors.HexColor("#0284c7")  # Scientific Sky Blue
        text_color = colors.HexColor("#334155")

        title_style = ParagraphStyle(
            "ReportTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=primary_color,
            spaceAfter=4,
        )
        subtitle_style = ParagraphStyle(
            "ReportSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=15,
            textColor=secondary_color,
            spaceAfter=12,
        )
        meta_style = ParagraphStyle(
            "ReportMeta",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=14,
        )
        h2_style = ParagraphStyle(
            "ReportH2",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=17,
            textColor=primary_color,
            spaceBefore=14,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "ReportBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=text_color,
            spaceAfter=8,
        )
        ref_style = ParagraphStyle(
            "ReportRef",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor("#475569"),
            spaceAfter=4,
        )

        story = []

        # 1. Header
        story.append(Paragraph(req.title, title_style))
        if req.subtitle:
            story.append(Paragraph(req.subtitle, subtitle_style))

        date_str = datetime.now(UTC).strftime("%B %d, %Y - %H:%M UTC")
        story.append(
            Paragraph(
                f"Generated by: <b>{req.author_name or 'BioInsight AI'}</b> | Date: {date_str} | Platform: BioInsight AI Research Suite",
                meta_style,
            )
        )
        story.append(HRFlowable(width="100%", thickness=1.5, color=secondary_color, spaceAfter=14))

        # 2. Executive Summary
        story.append(Paragraph("Executive Scientific Summary", h2_style))
        story.append(Paragraph(req.summary.replace("\n", "<br/>"), body_style))
        story.append(Spacer(1, 10))

        # 3. Dynamic Sections
        for sec in req.sections:
            story.append(Paragraph(sec.title, h2_style))
            story.append(Paragraph(sec.content.replace("\n", "<br/>"), body_style))

            if sec.table_data and len(sec.table_data) > 0:
                table_flowable_data = []
                for row_idx, row in enumerate(sec.table_data):
                    formatted_row = [
                        Paragraph(
                            f"<b>{cell}</b>" if row_idx == 0 else str(cell),
                            body_style,
                        )
                        for cell in row
                    ]
                    table_flowable_data.append(formatted_row)

                t = Table(table_flowable_data, colWidths=None)
                t.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                            ("TEXTCOLOR", (0, 0), (-1, 0), primary_color),
                            ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#94a3b8")),
                            ("TOPPADDING", (0, 0), (-1, -1), 4),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ]
                    )
                )
                story.append(t)
                story.append(Spacer(1, 10))

        # 4. References & Provenance
        if req.references:
            story.append(HRFlowable(width="100%", thickness=0.8, color=colors.HexColor("#cbd5e1"), spaceBefore=12, spaceAfter=8))
            story.append(Paragraph("References & Scientific Provenance", h2_style))
            for ref in req.references:
                story.append(Paragraph(f"• {ref}", ref_style))

        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()

    def generate_docx(self, req: GenerateReportRequest) -> bytes:
        """Render an editable scientific research document in DOCX format using python-docx."""
        doc = Document()

        # Document Title
        doc.add_heading(req.title, level=0)
        if req.subtitle:
            p_sub = doc.add_paragraph()
            p_sub.add_run(req.subtitle).italic = True

        # Metadata
        date_str = datetime.now(UTC).strftime("%B %d, %Y")
        p_meta = doc.add_paragraph()
        p_meta.add_run(f"Author: {req.author_name or 'BioInsight AI'} | Date: {date_str} | Platform: BioInsight AI").font.size = 11

        # Executive Summary
        doc.add_heading("Executive Scientific Summary", level=1)
        doc.add_paragraph(req.summary)

        # Dynamic Sections
        for sec in req.sections:
            doc.add_heading(sec.title, level=1)
            doc.add_paragraph(sec.content)

            if sec.table_data and len(sec.table_data) > 0:
                table = doc.add_table(rows=len(sec.table_data), cols=len(sec.table_data[0]))
                table.style = "Table Grid"
                for r_idx, row in enumerate(sec.table_data):
                    for c_idx, cell in enumerate(row):
                        cell_para = table.cell(r_idx, c_idx).paragraphs[0]
                        cell_para.text = str(cell)
                        if r_idx == 0:
                            cell_para.runs[0].bold = True

        # References
        if req.references:
            doc.add_heading("References & Scientific Provenance", level=1)
            for ref in req.references:
                doc.add_paragraph(ref, style="List Bullet")

        buffer = io.BytesIO()
        doc.save(buffer)
        buffer.seek(0)
        return buffer.getvalue()
